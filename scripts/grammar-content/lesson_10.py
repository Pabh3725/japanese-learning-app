def pos(word, *others):
    """Từ chỉ vị trí, nhiễu là vị trí khác (câu hiện nghĩa nên chọn sai vị trí là sai)."""
    return f'[W:{",".join(others)}]{word}'


def s(*parts):
    return '|'.join(parts)


def plain(p):
    return p.split('{')[0].split(']')[-1]


def text(parts):
    return ''.join(plain(p) for p in parts)


def ans(parts, meaning, uses, q, qm, wrong):
    return (s(*parts), meaning, uses, (q, qm, wrong))


