def where(k, parts, meaning, uses, wrong_verb):
    qs, qm = Q3[k]
    t = text(parts)
    return ans(parts, meaning, uses, qs, qm, [f'はい、{t}', t[:-1] + 'か。', t.replace('に', 'を', 1).replace(wrong_verb[0], wrong_verb[1], 1)])


def wq(k, uses=()):
    qs, qm = Q3[k]
    return (qs.replace('どこ|に', 'どこ|' + NI, 1), qm, [A, *uses])


