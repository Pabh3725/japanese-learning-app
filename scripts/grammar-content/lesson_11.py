def s(*parts):
    return '|'.join(parts)


def plain(p):
    return p.split('{')[0].split(']')[-1]


def text(parts):
    return ''.join(plain(p) for p in parts)


def ctr(word, *wrong):
    """Từ đếm được hỏi; nhiễu là từ đếm khác (câu hiện nghĩa nên đếm sai loại là sai)."""
    return f'[W:{",".join(wrong)}]{word}'


def ans(parts, meaning, uses, q, qm, wrong=None):
    t = text(parts)
    if wrong is None:
        wrong = [f'はい、{t}', t[:-1] + 'か。']
    return (s(*parts), meaning, uses, (q, qm, wrong))


