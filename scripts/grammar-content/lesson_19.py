def s(*parts):
    return '|'.join(parts)


def ans(parts, meaning, uses, q, qm, wrong):
    return (s(*parts), meaning, uses, (q, qm, wrong))


def koto(*parts, neg=False):
    """～たことがあります／ありません."""
    return s(*parts, 'こと', GA, 'ありません' if neg else 'あります', '。')


