def ba(n, parts, meaning, uses, ta, bad):
    qs, qm = QB[n]
    t = ''.join(p.split('{')[0].split(']')[-1] for p in parts)
    flip = t.replace('はい', 'いいえ', 1) if t.startswith('はい') else t.replace('いいえ', 'はい', 1)
    return (s(*parts), meaning, [*uses], (qs, qm, [flip, '*' + t.replace(ta, bad, 1), t.replace('ことが', 'ことを', 1)]))


