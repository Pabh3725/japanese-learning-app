def s(*parts):
    return '|'.join(parts)


def ans(parts, meaning, uses, q, qm, wrong):
    return (s(*parts), meaning, uses, (q, qm, wrong))


def kd(*parts, neg=False):
    """～ことができます／できません."""
    return s(*parts, 'こと', GA, 'できません' if neg else 'できます', '。')


