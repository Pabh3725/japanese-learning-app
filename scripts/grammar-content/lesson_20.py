DOCCHI = '[W:どこ,どれ,誰]どっち'


def s(*parts):
    return '|'.join(parts)


def f(word, *wrong):
    """Chỗ hỏi thể thông thường với nhiễu soạn tay (dạng sai đánh *)."""
    return f'[F:{",".join(wrong)}]{word}'


def ans(parts, meaning, uses, q, qm, wrong):
    return (s(*parts), meaning, uses, (q, qm, wrong))


