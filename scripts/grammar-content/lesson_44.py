def W(word, *wrong):
    return f"[W:{','.join(wrong)}]{word}"


def NA(word, tail='すぎます'):
    """Tính từ な + すぎます: nhiễu dạng sai."""
    return W(word + tail, '*' + word + 'な' + tail, '*' + word + 'に' + tail, '*' + word + 'く' + tail)


def s(*parts):
    return '|'.join(parts)


def ans(parts, meaning, uses, q, qm, wrong):
    return (s(*parts), meaning, uses, (q, qm, wrong))


