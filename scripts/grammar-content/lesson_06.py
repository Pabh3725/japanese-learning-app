def s(*parts):
    return '|'.join(parts)


def text(parts):
    return ''.join(p.split('{')[0].split(']')[-1] for p in parts)


def ans(parts, meaning, uses, q, qm, wrong=None):
    """Câu đáp. Câu đáp sai mặc định: thêm はい; biến thành câu hỏi; thay trợ từ được hỏi bằng へ (luôn sai ở đây)."""
    t = text(parts)
    if wrong is None:
        swapped = ''.join('へ' if p.startswith('[P') else p.split('{')[0].split(']')[-1] for p in parts)
        wrong = [f'はい、{t}', t[:-1] + 'か。', swapped]
    return (s(*parts), meaning, uses, (q, qm, wrong))


