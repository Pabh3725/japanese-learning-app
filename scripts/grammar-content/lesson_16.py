def s(*parts):
    return '|'.join(parts)


def plain(p):
    return p.split('{')[0].split(']')[-1]


def text(parts):
    return ''.join(plain(p) for p in parts)


def ans(parts, meaning, uses, q, qm, wrong):
    return (s(*parts), meaning, uses, (q, qm, wrong))


